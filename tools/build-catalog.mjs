#!/usr/bin/env node
// Regenerates CATALOG.md from the frontmatter of every skills/*/SKILL.md.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const skillsDir = path.join(root, 'skills');
const rows = [];

for (const dir of fs.readdirSync(skillsDir).sort()) {
  const file = path.join(skillsDir, dir, 'SKILL.md');
  if (!fs.existsSync(file)) continue;
  const text = fs.readFileSync(file, 'utf8');
  const fm = text.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '';
  const name = (fm.match(/^name:\s*(.*)$/m)?.[1] ?? dir).replace(/^["']|["']$/g, '').trim();
  const desc = (fm.match(/^description:\s*(.*)$/m)?.[1] ?? '').replace(/^["']|["']$/g, '').replace(/\s+/g, ' ').trim();
  const files = fs.readdirSync(path.join(skillsDir, dir)).length;
  rows.push({ name, dir, desc: desc.length > 160 ? desc.slice(0, 157) + '…' : desc, files });
}

const total = rows.length;
const out = [
  '# Catalog',
  '',
  `${total} skills. Generated by \`tools/build-catalog.mjs\` — do not edit by hand.`,
  '',
  '| Skill | What it does | Files |',
  '|---|---|---|',
  ...rows.map(r => `| \`${r.name}\` | ${r.desc.replace(/\|/g, '\\|')} | ${r.files} |`),
  '',
];
fs.writeFileSync(path.join(root, 'CATALOG.md'), out.join('\n'));
console.log(`wrote CATALOG.md with ${total} skills`);
